const PDFDocument = require('pdfkit');

const NAVY = '#16233B';
const RUST = '#B6400E';
const MUTED = '#5B6B80';
const LINE = '#D6DEE8';
const PAGE_LEFT = 48;
const PAGE_RIGHT = 547;

function formatDate(value) {
  if (!value) return 'Not recorded';
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? 'Not recorded' : date.toLocaleString('en-US', { timeZone: 'UTC' }) + ' UTC';
}

function formatRisk(value) {
  return Number.isFinite(value) ? `${Math.round(value)} / 100` : 'No score';
}

function drawTimeline(doc, points) {
  const left = PAGE_LEFT + 15;
  const top = doc.y + 14;
  const width = PAGE_RIGHT - left - 15;
  const height = 150;
  const bottom = top + height;
  doc.save();
  doc.strokeColor(LINE).lineWidth(1).moveTo(left, top).lineTo(left, bottom).lineTo(left + width, bottom).stroke();
  [35, 65].forEach((threshold) => {
    const y = bottom - (threshold / 100) * height;
    doc.save().dash(4, { space: 3 }).strokeColor(RUST).lineWidth(0.8)
      .moveTo(left, y).lineTo(left + width, y).stroke().restore();
    doc.fillColor(MUTED).fontSize(8).text(String(threshold), left - 17, y - 4, { width: 14, align: 'right' });
  });

  const validPoints = points.filter((point) => Number.isFinite(point.risk));
  if (validPoints.length > 0) {
    doc.strokeColor(NAVY).lineWidth(2);
    validPoints.forEach((point, index) => {
      const x = left + (validPoints.length === 1 ? width / 2 : (index / (validPoints.length - 1)) * width);
      const y = bottom - (Math.max(0, Math.min(100, point.risk)) / 100) * height;
      if (index === 0) doc.moveTo(x, y);
      else doc.lineTo(x, y);
    });
    doc.stroke();
  } else {
    doc.fillColor(MUTED).fontSize(10).text('No risk scores were recorded for this session.', left + 8, top + height / 2 - 5, { width: width - 16, align: 'center' });
  }
  doc.restore();
  doc.y = bottom + 18;
}

function buildAuditReport({ session, summary, timeline, reasonCounts, feedback }) {
  const doc = new PDFDocument({ size: 'A4', margins: { top: 48, right: 48, bottom: 55, left: 48 }, info: { Title: 'KYCShield Audit Report', Author: 'KYCShield' } });

  const drawFooter = () => {
    const previousY = doc.y;
    doc.save().fontSize(8).fillColor(MUTED)
      .text('Generated by KYCShield. Only scores are stored; no raw audio or video.', PAGE_LEFT, doc.page.height - 34, {
        width: PAGE_RIGHT - PAGE_LEFT, align: 'center', lineBreak: false
      }).restore();
    doc.y = previousY;
  };
  doc.on('pageAdded', drawFooter);
  drawFooter();

  doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(22).text('KYCShield Audit Report', { continued: false });
  doc.moveDown(0.35).fillColor(RUST).fontSize(10).text(`Session ${session.roomId}`);
  doc.moveDown(0.2).strokeColor(LINE).lineWidth(1).moveTo(PAGE_LEFT, doc.y + 4).lineTo(PAGE_RIGHT, doc.y + 4).stroke();
  doc.moveDown(0.8);

  const metrics = [
    ['Report date', formatDate(new Date())],
    ['Started', formatDate(session.startedAt || session.createdAt)],
    ['Ended', formatDate(session.endedAt)],
    ['Duration', `${summary.durationSec || 0} seconds`],
    ['Decision', session.decision || 'pending'],
    ['Final label', summary.finalLabel || 'Waiting for data'],
    ['Peak risk', formatRisk(summary.peakRisk)],
    ['Average risk', formatRisk(summary.avgRisk)],
    ['Score count', String(summary.scoreCount || 0)],
    ['Virtual camera', session.virtualCamera?.flagged ? `Detected (${session.virtualCamera.label || 'label unavailable'})` : 'Not detected']
  ];
  const metricsTop = doc.y;
  metrics.forEach(([label, value], index) => {
    const column = index % 2;
    const row = Math.floor(index / 2);
    const x = PAGE_LEFT + column * 250;
    const y = metricsTop + row * 43;
    doc.fillColor(MUTED).font('Helvetica').fontSize(8).text(label.toUpperCase(), x, y, { width: 220 });
    doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(10).text(String(value), x, y + 12, { width: 220, height: 24, ellipsis: true });
  });
  doc.y = metricsTop + 5 * 43 + 10;

  if (summary.mockUsed) {
    doc.roundedRect(PAGE_LEFT, doc.y, PAGE_RIGHT - PAGE_LEFT, 42, 6).fill(RUST);
    doc.fillColor('#FFFFFF').font('Helvetica-Bold').fontSize(10)
      .text('Scores in this report came from MOCK mode and are simulated.', PAGE_LEFT + 12, doc.y + 14, { width: PAGE_RIGHT - PAGE_LEFT - 24, align: 'center' });
    doc.y += 55;
  }

  doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(13).text('Risk timeline');
  doc.y += 3;
  drawTimeline(doc, timeline || []);

  doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(13).text('Top reasons');
  doc.moveDown(0.45);
  if (!reasonCounts?.length) {
    doc.fillColor(MUTED).font('Helvetica').fontSize(9).text('No reason signals were recorded.');
  } else {
    const tableLeft = PAGE_LEFT + 4;
    const countLeft = PAGE_RIGHT - 60;
    doc.fillColor(MUTED).font('Helvetica-Bold').fontSize(8)
      .text('REASON', tableLeft, doc.y, { width: countLeft - tableLeft - 8 });
    doc.text('COUNT', countLeft, doc.y, { width: 52, align: 'right' });
    doc.y += 15;
    doc.strokeColor(LINE).lineWidth(0.7).moveTo(tableLeft, doc.y).lineTo(PAGE_RIGHT - 4, doc.y).stroke();
    doc.y += 5;
    reasonCounts.slice(0, 8).forEach((item) => {
      const rowY = doc.y;
      doc.fillColor(NAVY).font('Helvetica').fontSize(9)
        .text(String(item.text || ''), tableLeft, rowY, { width: countLeft - tableLeft - 8, height: 24, ellipsis: true });
      doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(9)
        .text(String(item.count || 0), countLeft, rowY, { width: 52, align: 'right' });
      doc.y = rowY + 22;
      doc.strokeColor(LINE).lineWidth(0.5).moveTo(tableLeft, doc.y).lineTo(PAGE_RIGHT - 4, doc.y).stroke();
      doc.y += 4;
    });
  }

  doc.moveDown(0.6).fillColor(NAVY).font('Helvetica-Bold').fontSize(13).text('Liveness challenges');
  doc.moveDown(0.4);
  const challenges = (session.challenges || []).slice(-100);
  if (!challenges.length) {
    doc.fillColor(MUTED).font('Helvetica').fontSize(9).text('No liveness challenges were recorded.');
  } else {
    challenges.forEach((challenge) => {
      doc.fillColor(NAVY).font('Helvetica').fontSize(9)
        .text(`${challenge.type}: ${challenge.result} — ${formatDate(challenge.at)}`, PAGE_LEFT + 4, doc.y, { width: PAGE_RIGHT - PAGE_LEFT - 8 });
      doc.moveDown(0.25);
    });
  }

  doc.moveDown(0.6).fillColor(NAVY).font('Helvetica-Bold').fontSize(13).text('Analyst feedback');
  doc.moveDown(0.4);
  if (!feedback) {
    doc.fillColor(MUTED).font('Helvetica').fontSize(9).text('No analyst feedback recorded.');
  } else {
    doc.fillColor(NAVY).font('Helvetica').fontSize(9).text(`Verdict: ${feedback.verdict}`);
    doc.moveDown(0.25).text(`Risk at feedback: ${formatRisk(feedback.riskAtDecision)}; label: ${feedback.label || 'Waiting for data'}`);
    if (feedback.note) doc.moveDown(0.35).fillColor(MUTED).text(`Note: ${feedback.note}`, { width: PAGE_RIGHT - PAGE_LEFT });
  }

  return doc;
}

module.exports = { buildAuditReport };
